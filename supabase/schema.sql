-- Мессенджер v2: тестовый общий чат на Supabase.
-- Включите Anonymous Sign-Ins в Authentication -> Sign In / Providers (или Auth settings).
-- Затем выполните этот SQL в SQL Editor.
-- ВАЖНО: это тестовый общий чат. Все вошедшие участники могут читать все сообщения.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Пользователь',
  created_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  room_id uuid not null default '00000000-0000-4000-8000-000000000001',
  sender_id uuid not null references auth.users(id) on delete cascade,
  display_name text not null default 'Пользователь',
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now()
);

create index if not exists messages_room_created_idx
  on public.messages (room_id, created_at);

alter table public.profiles enable row level security;
alter table public.messages enable row level security;

drop policy if exists "Users can read profiles" on public.profiles;
create policy "Users can read profiles"
  on public.profiles for select to authenticated using (true);

drop policy if exists "Users can insert own profile" on public.profiles;
create policy "Users can insert own profile"
  on public.profiles for insert to authenticated with check (auth.uid() = id);

drop policy if exists "Users can update own profile" on public.profiles;
create policy "Users can update own profile"
  on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "Authenticated users read test room" on public.messages;
create policy "Authenticated users read test room"
  on public.messages for select to authenticated
  using (room_id = '00000000-0000-4000-8000-000000000001');

drop policy if exists "Authenticated users send to test room as themselves" on public.messages;
create policy "Authenticated users send to test room as themselves"
  on public.messages for insert to authenticated
  with check (
    auth.uid() = sender_id
    and room_id = '00000000-0000-4000-8000-000000000001'
  );

